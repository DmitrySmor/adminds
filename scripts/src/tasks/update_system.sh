#!/usr/bin/env bash

set -euo pipefail

# ============================
#  Обновление списка пакетов
# ============================
# Обновляет локальный список доступных пакетов
# из настроенных репозиториев Debian.
#
# После успешного выполнения выводится подтверждение обновления.
update_system() {
    apt-get update
    log_success "Список пакетов обновлён"
}
